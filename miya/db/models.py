class ConversationWindow(Base):
    """A flushed slice of one chat's conversation, extracted as a unit (spec §7B).

    The userbot stores each message as its own interaction; a window groups the
    consecutive ones and is what actually goes to the extractor, so a debt
    mentioned across three messages is understood as one fact. Extraction runs
    through the Batch API (half price), hence the explicit lifecycle.
    """

    __tablename__ = "conversation_windows"

    id: Mapped[int] = mapped_column(primary_key=True)
    tg_chat_id: Mapped[int] = mapped_column(sa.BigInteger, nullable=False)
    person_id: Mapped[int | None] = mapped_column(
        sa.ForeignKey("people.id", ondelete="SET NULL")
    )
    started_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False
    )
    ended_at: Mapped[datetime] = mapped_column(sa.DateTime(timezone=True), nullable=False)
    message_count: Mapped[int] = mapped_column(sa.Integer, nullable=False)
    char_count: Mapped[int] = mapped_column(sa.Integer, nullable=False)
    # The rendered [ME] / [THEM (Name)] transcript handed to the extractor.
    text: Mapped[str] = mapped_column(sa.Text, nullable=False)
    status: Mapped[e.WindowStatus] = mapped_column(
        WINDOW_STATUS, nullable=False, server_default=e.WindowStatus.pending.value
    )
    # Anthropic Message Batches identifiers: the job, and this window's slot.
    batch_id: Mapped[str | None] = mapped_column(sa.Text)
    custom_id: Mapped[str] = mapped_column(sa.Text, unique=True, nullable=False)
    attempts: Mapped[int] = mapped_column(sa.Integer, nullable=False, server_default="0")
    submitted_at: Mapped[datetime | None] = mapped_column(sa.DateTime(timezone=True))
    applied_at: Mapped[datetime | None] = mapped_column(sa.DateTime(timezone=True))
    # The instant path (build step 2): a private chat, or a group window with
    # a message aimed at the owner, is extracted in real time by the window
    # job rather than waiting for the next batch. Cleared if that keeps
    # failing, so the window falls back onto the batch ladder.
    instant: Mapped[bool] = mapped_column(
        sa.Boolean, nullable=False, server_default=sa.false()
    )
    created_at: Mapped[datetime] = created_at_column()

    __table_args__ = (
        sa.Index("ix_conversation_windows_status", "status", "created_at"),
        sa.Index("ix_conversation_windows_batch", "batch_id"),
        # Foreign keys that cascade or set null are indexed (WP-23, 0016).
        sa.Index("ix_conversation_windows_person", "person_id"),
    )


class Interaction(Base):
    """Every input lands here first, before extraction."""

    __tablename__ = "interactions"

    id: Mapped[int] = mapped_column(primary_key=True)
    source: Mapped[e.InteractionSource] = mapped_column(
        INTERACTION_SOURCE, nullable=False
    )
    direction: Mapped[e.Direction] = mapped_column(
        DIRECTION, nullable=False, server_default=e.Direction.na.value
    )
    person_id: Mapped[int | None] = mapped_column(
        sa.ForeignKey("people.id", ondelete="SET NULL")
    )
    tg_chat_id: Mapped[int | None] = mapped_column(sa.BigInteger)
    occurred_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False
    )
    raw_text: Mapped[str | None] = mapped_column(sa.Text)
    transcript: Mapped[str | None] = mapped_column(sa.Text)
    # {type, path, mime, size, caption, processed, sha256, ...}
    media: Mapped[dict[str, Any] | None] = mapped_column(JSONB)
    summary: Mapped[str | None] = mapped_column(sa.Text)
    meta: Mapped[dict[str, Any] | None] = mapped_column("metadata", JSONB)
    # When the codes in this row's text were indexed into code_mentions
    # (WP-30, 0017); NULL = not yet.
    codes_indexed_at: Mapped[datetime | None] = mapped_column(sa.DateTime(timezone=True))
    # WP-55: when this row's passages were last (re)written; NULL = pending.
    search_indexed_at: Mapped[datetime | None] = mapped_column(sa.DateTime(timezone=True))
    processed: Mapped[bool] = mapped_column(
        sa.Boolean, nullable=False, server_default=sa.false()
    )
    # Set when extraction failed validation twice — data is never dropped.
    needs_review: Mapped[bool] = mapped_column(
        sa.Boolean, nullable=False, server_default=sa.false()
    )
    created_at: Mapped[datetime] = created_at_column()

    # Set once a userbot message has been claimed by a conversation window;
    # the window owns extraction for every message it contains (spec §7B).
    window_id: Mapped[int | None] = mapped_column(
        sa.ForeignKey("conversation_windows.id", ondelete="SET NULL")
    )

    person: Mapped[Person | None] = relationship(lazy="raise")

    __table_args__ = (
        sa.Index("ix_interactions_occurred_at", "occurred_at"),
        sa.Index("ix_interactions_chat_occurred", "tg_chat_id", "occurred_at"),
        sa.Index("ix_interactions_person", "person_id"),
        # The per-person timeline: newest first, paged by occurred_at.
        sa.Index(
            "ix_interactions_person_occurred",
            "person_id",
            sa.text("occurred_at DESC"),
        ),
        sa.Index(
            "ix_interactions_unprocessed",
            "created_at",
            postgresql_where=sa.text("processed = false"),
        ),
        # The window flush job asks "which userbot messages are unclaimed?"
        # every few minutes; keep that off a sequential scan.
        sa.Index(
            "ix_interactions_unwindowed",
            "tg_chat_id",
            "occurred_at",
            postgresql_where=sa.text("window_id IS NULL AND source = 'telegram_userbot'"),
        ),
        # Call-recording dedupe: hash lookups happen once a minute (spec §7C).
        sa.Index(
            "ix_interactions_media_sha256",
            sa.text("(media ->> 'sha256')"),
            postgresql_where=sa.text("source = 'phone_call'"),
        ),
        # Phone-event dedupe (build step 6): one row per call-log entry or
        # SMS, ever. The key is minted on the phone, so a retried batch lands
        # here instead of becoming a second interaction — the unique index,
        # not the ingester's pre-select, is the idempotency guarantee.
        sa.Index(
            "ux_interactions_event_key",
            sa.text("(media ->> 'event_key')"),
            unique=True,
            postgresql_where=sa.text("media ->> 'event_key' IS NOT NULL"),
        ),
        # Reinstall-safe dedupe (WP-11): the event key carries the device id,
        # which a reinstall re-mints; the content key is the message itself.
        sa.Index(
            "ux_interactions_content_key",
            sa.text("(media ->> 'content_key')"),
            unique=True,
            postgresql_where=sa.text("media ->> 'content_key' IS NOT NULL"),
        ),
        # One row per Telegram message (WP-21): the catch-up sweep and the
        # live handler may ingest the same message at once.
        sa.Index(
            "ux_interactions_tg_message",
            "tg_chat_id",
            sa.text("((metadata ->> 'tg_message_id')::bigint)"),
            unique=True,
            postgresql_where=sa.text(
                "source = 'telegram_userbot' AND metadata ? 'tg_message_id'"
            ),
        ),
        sa.Index(
            "ix_interactions_codes_unindexed",
            "id",
            postgresql_where=sa.text("codes_indexed_at IS NULL"),
        ),
        sa.Index(
            "ix_interactions_unindexed",
            "id",
            postgresql_where=sa.text("search_indexed_at IS NULL"),
        ),
        sa.Index(
            "ix_interactions_money_notice_pending",
            "occurred_at",
            postgresql_where=sa.text(
                "(metadata ? 'money_notice') AND NOT (metadata ? 'money_notified')"
            ),
        ),
        # Foreign keys that cascade or set null are indexed (WP-23, 0016).
        sa.Index("ix_interactions_window", "window_id"),
    )


